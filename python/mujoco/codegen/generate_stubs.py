def replace(text: str, old: str, new: str, count: int = 1) -> str:
  if text.count(old) != count:
    raise ValueError(
      f'Expected {count} occurrences of {old!r}, got {text.count(old)}'
    )
  return text.replace(old, new)


def macros():
  source = (ROOT / 'mujoco/indexer_xmacro.h').read_text()
  blocks = {}
  for block in re.split(r'(?=^#define )', source, flags=re.MULTILINE):
    match = re.match(r'#define (\w+)', block)
    if match:
      blocks[match.group(1)] = block
  views = {}
  accessors = {'MjModel': {}, 'MjData': {}}
  bind = {'MjModel': {}, 'MjData': {}}
  for kind in ('Model', 'Data'):
    cls = 'Mj' + kind
    prefix = 'MJ' + kind.upper()
    for name, field, macro in re.findall(
      r'XGROUP\(\s*(Mj\w+Views),\s*(\w+),\s*\w+,\s*(\w+)\s*\)',
      blocks[prefix + '_VIEW_GROUPS'],
    ):
      fields = {}
      for dtype, pre, var in re.findall(
        r'\bX\(\s*(\w+),\s*(\w*),\s*(\w+)\s*,', blocks[macro]
      ):
        fields[var] = {
          'mjtNum': ARRAY,
          'float': 'numpy.typing.NDArray[numpy.float32]',
          'int': 'numpy.typing.NDArray[numpy.int32]',
          'mjtByte': 'numpy.typing.NDArray[numpy.uint8]',
          'mjtBool': 'numpy.typing.NDArray[numpy.uint8]',
          'mjtSize': 'numpy.typing.NDArray[numpy.int64]',
        }[dtype]
      views['_' + name] = fields
      accessors[cls][field] = '_' + name
    for spec, field in re.findall(
      r'XGROUP\(\s*(mjs\w+),\s*(\w+)\s*\)',
      blocks[prefix + '_BIND_GROUPS'],
    ):
      bind[cls][spec] = accessors[cls][field]
    for field, alias in re.findall(
      r'XGROUP\(\s*(\w+),\s*(\w+),\s*\w+\s*\)',
      blocks[prefix + '_VIEW_GROUPS_ALTNAMES'],
    ):
      accessors[cls][alias] = accessors[cls][field]
  return views, accessors, bind


def correct_structs(text: str) -> str:
  views, accessors, bind = macros()
  text = replace(
    text, 'def stat(self) -> ...:', 'def stat(self) -> MjStatistic:'
  )
  text = text.replace(
    'typing.ClassVar[tuple]', 'typing.ClassVar[builtins.tuple]'
  )
  text = text.replace(
    'def active(self, arg1: typing.SupportsInt | typing.SupportsIndex) -> int:',
    'def active(self, arg1: typing.SupportsInt | typing.SupportsIndex) -> None:',
  )
  text = 'import builtins\n' + text
  text = text.replace(
    'vfs: ... = None', 'vfs: mujoco._specs.MjVfs | None = None'
  )
  tree = ast.parse(text)
  lines = text.splitlines()
  for cls in (
    c
    for c in tree.body
    if isinstance(c, ast.ClassDef) and c.name in ('MjModel', 'MjData')
  ):
    for method in (m for m in cls.body if isinstance(m, ast.FunctionDef)):
      index = method.lineno - 1
      line = lines[index]
      if method.name in accessors[cls.name]:
        lines[index] = replace(
          line, '-> ...:', f'-> {accessors[cls.name][method.name]}:'
        )
      elif method.name == 'bind_scalar':
        spec = re.search(r'spec: (mjs\w+)_ = None', line)
        if spec is None or spec.group(1) not in bind[cls.name]:
          raise ValueError(f'Unknown bind_scalar overload: {line}')
        lines[index] = line.replace(
          spec.group(0), f'spec: mujoco._specs.Mjs{spec.group(1)[3:]}'
        ).replace('-> ...:', f'-> {bind[cls.name][spec.group(1)]}:')
      elif method.name == 'bind':
        for decorator in method.decorator_list:
          if isinstance(decorator, ast.Name) and decorator.id == 'staticmethod':
            lines[decorator.lineno - 1] = ''
        header = []
        for spec, view in bind[cls.name].items():
          header += [
            '    @typing.overload',
            f'    def bind(self, specs: mujoco._specs.Mjs{spec[3:]}) -> {view}: ...',
          ]
        spec_union = ' | '.join(
          'mujoco._specs.Mjs' + spec[3:] for spec in bind[cls.name]
        )
        header += [
          '    @typing.overload',
          f'    def bind(self, specs: collections.abc.Sequence[{spec_union}]) -> mujoco._MjBind{cls.name[2:]}: ...',
        ]
        end_lineno = method.end_lineno
        if end_lineno is None:
          raise ValueError(f'Missing source span for {cls.name}.bind')
        lines[index] = '\n'.join(header)
        lines[end_lineno - 1] = ''
        for i in range(index + 1, end_lineno - 1):
          lines[i] = ''
      elif method.name in (
        'from_xml_string',
        'from_xml_path',
        'from_binary_path',
      ):
        pass
      elif method.name not in accessors[cls.name] and '-> ...:' in line:
        raise ValueError(f'Unknown native return type: {line}')
      if (
        method.name not in ('bind', 'bind_scalar')
        and method.name not in accessors[cls.name]
      ):
        if (
          'numpy.typing.NDArray[numpy.float64]' in line
          and method.name not in ('__init__',)
        ):
          # Model and data fields use mjtNum, unlike fixed-double spec fields.
          lines[index] = lines[index].replace(
            'numpy.typing.NDArray[numpy.float64]', f'({ARRAY})'
          )
  text = '\n'.join(lines) + '\n'
  props = []
  for name, fields in views.items():
    props.append(f'class {name}:')
    props += [
      '  @property',
      '  def id(self) -> int: ...',
      '  @property',
      '  def name(self) -> str: ...',
    ]
    for field, dtype in fields.items():
      props += [
        '  @property',
        f'  def {field}(self) -> {dtype}: ...',
        f'  @{field}.setter',
        f'  def {field}(self, value: numpy.typing.ArrayLike) -> None: ...',
      ]
  return text + '\n' + '\n'.join(props) + '\n'


def correct_specs(text: str) -> str:
  orientation = 'typing.Annotated[list[float], "FixedSize(4)"]'
  text = replace(
    text,
    '    @staticmethod\n    def resolve_orientation(degree: bool, sequence: MjCharVec = None, orientation: MjsOrientation) -> '
    + orientation
    + ':',
    '    @staticmethod\n    @typing.overload\n    def resolve_orientation(degree: bool, sequence: MjCharVec | None, orientation: MjsOrientation) -> '
    + orientation
    + ':\n        ...\n    @staticmethod\n    @typing.overload\n    def resolve_orientation(degree: bool, *, orientation: MjsOrientation, sequence: MjCharVec | None = None) -> '
    + orientation
    + ':',
  )
  text = text.replace(
    'default: MjsDefault = None', 'default: MjsDefault | None = None'
  )
  text = text.replace('vfs: MjVfs = None', 'vfs: MjVfs | None = None')
  text = text.replace(
    'default: MjsFrame = None', 'default: MjsFrame | None = None'
  )
  text = text.replace(
    'def copy_during_attach(self, arg1: bool) -> int:',
    'def copy_during_attach(self, arg1: bool) -> None:',
  )
  muscle = re.search(
    r'    def set_to_muscle\(self, timeconst: (.+?) = \[-1.0, -1.0\], tausmooth: (.+?), (range: .+?)\) -> None:',
    text,
  )
