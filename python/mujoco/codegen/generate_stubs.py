def replace(text: str, old: str, new: str, count: int = 1) -> str:
  if text.count(old) != count:
    raise ValueError(
      f'Expected {count} occurrences of {old!r}, got {text.count(old)}'
    )
  return text.replace(old, new)


def add_docs(text: str, module: str) -> str:
  docs = DOCS.get(module, {})
  if not docs:
    return text
  lines = text.splitlines(keepends=True)
  targets = {}
  for node in ast.parse(text).body:
    if not isinstance(node, (ast.ClassDef, ast.FunctionDef)):
      continue
    if node.name in docs:
      targets[node.name] = node
    if isinstance(node, ast.ClassDef):
      for member in node.body:
        if not isinstance(member, (ast.ClassDef, ast.FunctionDef)):
          continue
        name = f'{node.name}.{member.name}'
        if name in docs and name not in targets:
          targets[name] = member
  if docs.keys() != targets.keys():
    raise ValueError(
      f'Missing documentation targets in {module}: {docs.keys() - targets.keys()}'
    )
  for name, node in sorted(
    targets.items(), key=lambda item: item[1].lineno, reverse=True
  ):
    body = node.body[0]
    existing = ast.get_docstring(node, clean=False)
    inline = (
      isinstance(node, ast.FunctionDef) and ': ...\n' in lines[body.lineno - 1]
    )
    indent = ' ' * (node.col_offset + 4 if inline else body.col_offset)
    content = (existing.strip() + '\n\n' if existing else '') + docs[name]
    source = (
      f'{indent}"""' + content.replace('\n', '\n' + indent) + f'\n{indent}"""\n'
    )
    if existing is not None:
      lines[body.lineno - 1 : body.end_lineno] = [source]
    elif inline:
      lines[body.lineno - 1] = replace(
        lines[body.lineno - 1], ': ...\n', ':\n' + source
      )
    elif isinstance(node, ast.ClassDef):
      first = (
        body.decorator_list[0].lineno
        if isinstance(body, (ast.ClassDef, ast.FunctionDef))
        and body.decorator_list
        else body.lineno
      )
      lines.insert(first - 1, source)
    elif lines[body.lineno - 1].strip() == '...':
      lines[body.lineno - 1] = source
    else:
      raise ValueError(f'Unexpected documentation target: {module}.{name}')
  return ''.join(lines)


