def parts(text: str) -> list[str]:
  """Split a C++ macro argument list, including nested sizeof(...)."""
  fields = []
  depth = 0
  quoted = False
  start = 0
  for pos, char in enumerate(text):
    if char == '"' and (pos == 0 or text[pos - 1] != '\\'):
      quoted = not quoted
    if quoted:
      continue
    if char == '(':
      depth += 1
    elif char == ')':
      depth -= 1
    elif char == ',' and not depth:
      fields.append(text[start:pos].strip())
      start = pos + 1
  fields.append(text[start:].strip())
  return fields


def argument(field: str, implot: bool, enum_types: dict[str, str]) -> str:
  assert field.startswith('(') and field.endswith(')'), field
  cpp_type, name, default = parts(field[1:-1])
  if keyword.iskeyword(name):
    name += '_'
  types = {
    'ImString': 'str',
    'std::string': 'str',
    'bool': 'bool',
    'int': 'int',
    'long': 'int',
    'unsigned int': 'int',
    'ImGuiID': 'int',
    'ImU32': 'int',
    'ImTextureRef': 'object',
    'ImGuiKeyChord': 'int | imgui.Key' if implot else 'int | Key',
    'ImGuiMouseButton': 'int | imgui.MouseButton'
    if implot
    else 'int | MouseButton',
    'ImGuiDragDropFlags': 'int | imgui.DragDropFlags'
    if implot
    else 'int | DragDropFlags',
    'float': 'float',
    'double': 'float',
    'const ImVec2&': 'imgui.Vec2' if implot else 'Vec2',
    'ImVec2': 'imgui.Vec2' if implot else 'Vec2',
    'const ImVec4&': 'imgui.Vec4' if implot else 'Vec4',
    'ImVec4': 'imgui.Vec4' if implot else 'Vec4',
    'const ImPlotPoint&': 'Point',
  }
  for enum in (
    ('ImAxis', 'Axis'),
    ('ImPlotScale', 'Scale'),
    ('ImPlotLocation', 'Location'),
    ('ImPlotCond', 'Cond'),
    ('ImGuiDir', 'Dir'),
    ('ImGuiCond', 'Cond'),
    ('ImGuiKey', 'Key'),
    ('ImGuiMouseCursor', 'MouseCursor'),
  ):
    types[enum[0]] = enum[1]
  types.update(enum_types)
  for prefix in ('ImGui', 'ImPlot'):
    if cpp_type.startswith(prefix) and cpp_type.endswith('Flags'):
      types[cpp_type] = 'int | ' + types[cpp_type].removeprefix('int | ')
  if cpp_type.startswith('std::vector<'):
    inner = cpp_type.removeprefix('std::vector<').removesuffix('>')
    value_type = {
      'float': 'float',
      'double': 'float',
      'int': 'int',
      'std::string': 'str',
    }[inner]
    py_type = f'Iterable[{value_type}]'
  elif cpp_type.endswith('*') or cpp_type == 'float&':
    py_type = types.get(
      cpp_type.removesuffix('*')
      .removesuffix('&')
      .strip()
      .removeprefix('const '),
      '',
    )
    if not py_type:
      raise ValueError(f'Unmapped pointer: {cpp_type}')
  else:
    py_type = types.get(cpp_type, '')
    if not py_type:
      raise ValueError(f'Unmapped type: {cpp_type}')
  if cpp_type == 'const float*' and name == 'ref_col':
    py_type = 'object'
  elif default.strip() == '= nullptr':
    py_type += ' | None'
  result = f'{name}: {py_type}'
  if default.strip().startswith('='):
    value = default.strip()[1:].strip()
    if value in ('true', 'false', 'nullptr'):
      value = {'true': 'True', 'false': 'False', 'nullptr': 'None'}[value]
    elif re.fullmatch(r'-?\d+(?:\.\d+)?f?', value):
      value = value.rstrip('f') if py_type in ('int', 'float') else '...'
    elif value.startswith('"') and value.endswith('"'):
      value = repr(ast.literal_eval(value))
    else:
      value = '...'
    result += f' = {value}'
  return result


def macros(source: str, implot: bool) -> list[tuple[str, list[str], str]]:
  result = []
  enum_types = {
    cpp.removesuffix('_'): name
    for cpp, name in re.findall(r'py::enum_<([^>]+)>\(m, "(\w+)"\)', source)
  }
  for line in source.splitlines():
    match = re.match(r'^  DEF(\d+)(_AS|_F)?\(', line)
    if not match:
      continue
    count, kind = int(match[1]), match[2]
    signature = (
      line.split(', {', 1)[0] if kind == '_F' else line.split(');', 1)[0]
    )
    raw = parts(signature[match.end() :])
    name = raw[1] if kind == '_AS' else raw[0]
    fields = raw[2:] if kind == '_AS' else raw[1:]
    if len(fields) != count:
      raise ValueError(f'Wrong argument count in {line}')
    args = [argument(field, implot, enum_types) for field in fields]
    if implot:
      ret = IMPLOT_RETURNS.get(name)
      if ret is None:
        if name.startswith(
          ('End', 'Setup', 'Set', 'Plot', 'Push', 'Pop', 'Tag')
        ) or name in {'Annotation', 'CancelPlotSelection', 'HideNextItem'}:
          ret = 'None'
        else:
          raise ValueError(f'Unclassified ImPlot result: {name}')
    else:
      ret = IMGUI_RETURNS.get(name)
      if name == 'BeginTabItem':
        ret = (
          'tuple[bool, bool]'
          if any(field.startswith('(bool*,') for field in fields)
          else 'bool'
        )
      if ret is None:
        if name in IMGUI_BOOL:
          ret = 'bool'
        elif name in IMGUI_FLOAT:
          ret = 'float'
        elif name.startswith(
          (
            'End',
            'Set',
            'Push',
            'Pop',
            'Text',
            'Value',
            'DockBuilder',
            'Separator',
            'TableSetup',
            'TableSet',
          )
        ) or name in {
          'Separator',
          'SameLine',
          'NewLine',
          'Spacing',
          'Dummy',
          'Indent',
          'Unindent',
          'AlignTextToFramePadding',
          'Bullet',
          'BulletText',
          'LabelText',
          'ProgressBar',
          'BeginGroup',
          'BeginDisabled',
          'BeginTooltip',
          'BeginItemTooltip',
          'TreePush',
          'TreePop',
          'OpenPopup',
          'CloseCurrentPopup',
          'Image',
          'Columns',
          'NextColumn',
          'TableNextRow',
          'TableHeader',
          'TableHeadersRow',
          'TableAngledHeadersRow',
          'ColorConvertRGBtoHSV',
          'ColorConvertHSVtoRGB',
          'ResetMouseDragDelta',
        }:
          ret = 'None'
        else:
          raise ValueError(f'Unclassified ImGui result: {name}')
    result.append((name, args, ret))
  return result


def enums(source: str) -> str:
  output = []
  for match in re.finditer(
    r'py::enum_<[^>]+>\(m, "(\w+)"\)(.*?);', source, re.S
  ):
    names = re.findall(r'\.value\("(\w+)"', match[2])
    if not names:
      raise ValueError(f'Empty enum {match[1]}')
    # The C++ name "None" is accessible with getattr, not Python dot syntax.
    output.append(f'class {match[1]}:')
    output.append(f'  __members__: ClassVar[dict[str, {match[1]}]]')
    output.extend(
      f'  {name}: ClassVar[{match[1]}]' for name in names if name != 'None'
    )
    output.extend(
      [
        '  def __init__(self, value: int) -> None: ...',
        '  def __int__(self) -> int: ...',
        '  def __index__(self) -> int: ...',
        '  @property',
        '  def name(self) -> str: ...',
        '  @property',
        '  def value(self) -> int: ...',
      ]
    )
    output.append('')
  return '\n'.join(output)


def generate(module: str) -> str:
  implot = module == 'implot'
  source = (ROOT / module / f'{module}.cc').read_text()
  intro = 'from collections.abc import Iterable\nfrom typing import ClassVar, overload\n'
  if implot:
    intro += (
      '\nfrom typing_extensions import Never\n'
      '\nfrom mujoco.experimental.dear_imgui import dear_imgui as imgui\n'
    )
  classes = IMPLOT_CLASSES if implot else IMGUI_CLASSES
  calls = macros(source, implot)
  by_name = defaultdict(list)
  for name, args, ret in calls:
    by_name[name].append((args, ret))
  funcs = []
  for name, variants in by_name.items():
    for args, ret in variants:
      if len(variants) > 1:
        funcs.append('@overload')
      signature = ', '.join(args)
      if name in UI_DOCS:
        funcs.append(
          f'def {name}({signature}) -> {ret}:\n  """{UI_DOCS[name]}"""'
        )
      else:
        funcs.append(f'def {name}({signature}) -> {ret}: ...')
    funcs.append('')
  text = (
    HEADER
    + '\n'
    + intro
    + '\n'
    + classes
    + '\n'
    + enums(source)
    + '\n'.join(funcs)
  )
  ast.parse(text)
  declared = {
    node.name
    for node in ast.parse(text).body
    if isinstance(node, (ast.ClassDef, ast.FunctionDef))
  }
  bound = set(re.findall(r'\bm\.def\(\s*"(\w+)"', source))
  bound.update(re.findall(r'^  py::class_<[^>]+>\(m, "(\w+)"', source, re.M))
  bound.update(re.findall(r'py::enum_<[^>]+>\(m, "(\w+)"', source))
  bound.update(by_name)
  if bound - declared:
    raise ValueError(f'{module}: missing bindings: {bound - declared}')
  classes = {}
  for node in ast.parse(text).body:
    if isinstance(node, ast.ClassDef):
      members = {
        item.name for item in node.body if isinstance(item, ast.FunctionDef)
      }
      members.update(
        item.target.id
        for item in node.body
        if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name)
      )
      classes[node.name] = members
  for cls, body in re.findall(
    r'^  py::class_<[^>]+>\(m, "(\w+)"\)(.*?);', source, re.M | re.S
  ):
    members = set(re.findall(r'\.def\w*\("(\w+)"', body))
    if members - classes[cls]:
      raise ValueError(
        f'{module}.{cls}: missing members: {members - classes[cls]}'
      )
  return text


